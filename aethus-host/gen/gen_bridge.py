# Generate the C bridge between the wasm2c translation of the web build and the embedded
# QuickJS that runs its wasm-bindgen glue.
#
#   python -I gen_bridge.py <wenilla.h> <out bridge_gen.c>
#
# From the header's `/* import: ... */` and `/* export: ... */` annotations it emits:
#   - one C function per glue import (module './wenilla_bg.js'): the wasm calls it, it converts
#     the arguments the way a browser's JS API does (i32 as a signed Number, i64 as a BigInt,
#     externref as the JS value it stands for), calls the glue's JS function, and converts the
#     result back;
#   - the import names, in order, for instantiation to look up in the glue's imports object;
#   - one QuickJS function per function export, which converts JS arguments the same way,
#     calls into the wasm under a trap guard and converts the result;
#   - the export table the WebAssembly.Instance's `exports` object is built from.
# WASI imports are answered in C (wasi.c) and only checked for here.
import re, sys

IMPORT_RE = re.compile(r"/\* import: '([^']*)' '([^']*)' \*/")
EXPORT_RE = re.compile(r"/\* export: '([^']*)' \*/")
PROTO_RE = re.compile(r'^(.*?)\s*\b([A-Za-z_][A-Za-z0-9_]*)\((.*)\);$')

GLUE_MODULE = './wenilla_bg.js'
WASI_MODULE = 'wasi_snapshot_preview1'
TYPES = {'u32', 'u64', 'f32', 'f64', 'wasm_rt_externref_t'}


def unescape(s):
    # wasm2c writes non-identifier bytes in names as \XX.
    return re.sub(r'\\([0-9A-Fa-f]{2})', lambda m: chr(int(m.group(1), 16)), s)


def parse(path):
    lines = open(path, encoding='utf-8').read().splitlines()
    imports, exports = [], []
    for i, line in enumerate(lines):
        m = IMPORT_RE.match(line)
        e = EXPORT_RE.match(line) if not m else None
        if not m and not e:
            continue
        p = PROTO_RE.match(lines[i + 1].strip())
        assert p, lines[i + 1]
        ret, cname, params = p.group(1).strip(), p.group(2), [x.strip() for x in p.group(3).split(',')]
        if m:
            module, name = unescape(m.group(1)), unescape(m.group(2))
            env = params[0]
            imports.append(dict(module=module, name=name, cname=cname, ret=ret, env=env, params=params[1:]))
        else:
            name = unescape(e.group(1))
            if ret.endswith('*'):
                exports.append(dict(name=name, cname=cname, kind=ret.rstrip('*').strip()))
            else:
                assert params[0] == 'w2c_wenilla*', lines[i + 1]
                exports.append(dict(name=name, cname=cname, kind='func', ret=ret, params=params[1:]))
    return imports, exports


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def emit(imports, exports, out):
    w = out.write
    w('/* Generated by aethus-host/gen/gen_bridge.py from wenilla.h. Do not edit. */\n')
    w('#include "bridge.h"\n\n')
    glue = [i for i in imports if i['module'] == GLUE_MODULE]
    other = [i for i in imports if i['module'] not in (GLUE_MODULE, WASI_MODULE)]
    assert not other, other
    for imp in glue:
        for t in imp['params']:
            assert t in TYPES, (imp['name'], t)
        assert imp['ret'] == 'void' or imp['ret'] in TYPES, (imp['name'], imp['ret'])

    w(f'const int bridge_import_count = {len(glue)};\n')
    w('const char *const bridge_import_names[] = {\n')
    for imp in glue:
        w(f'  {c_string(imp["name"])},\n')
    w('};\n\n')

    for idx, imp in enumerate(glue):
        params = ', '.join([f'{imp["env"]} env'] + [f'{t} a{k}' for k, t in enumerate(imp['params'])])
        w(f'{imp["ret"]} {imp["cname"]}({params}) {{\n')
        n = len(imp['params'])
        if n:
            conv = ', '.join(f'bridge_to_js_{t}(a{k})' for k, t in enumerate(imp['params']))
            w(f'  JSValue argv[{n}] = {{{conv}}};\n')
            w(f'  JSValue r = bridge_call_import({idx}, {n}, argv);\n')
        else:
            w(f'  JSValue r = bridge_call_import({idx}, 0, NULL);\n')
        if imp['ret'] == 'void':
            w('  bridge_drop_result(r);\n')
        else:
            w(f'  return bridge_result_{imp["ret"]}(r);\n')
        w('}\n\n')

    funcs = [e for e in exports if e['kind'] == 'func']
    for idx, exp in enumerate(funcs):
        for t in exp['params']:
            assert t in TYPES, (exp['name'], t)
        w(f'static JSValue export_{idx}(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv) {{\n')
        w('  (void)this_val;\n')
        for k, t in enumerate(exp['params']):
            w(f'  {t} a{k};\n')
            w(f'  if (bridge_arg_{t}(ctx, &a{k}, {k} < argc ? argv[{k}] : JS_UNDEFINED)) return JS_EXCEPTION;\n')
        call_args = ', '.join(['&g_inst'] + [f'a{k}' for k in range(len(exp['params']))])
        ret = exp['ret']
        if ret == 'void':
            w(f'  BRIDGE_GUARDED(ctx, {exp["cname"]}({call_args}));\n')
            w('  return JS_UNDEFINED;\n')
        else:
            w(f'  {ret} r;\n')
            w(f'  BRIDGE_GUARDED(ctx, r = {exp["cname"]}({call_args}));\n')
            if ret == 'struct wasm_multi_ii':
                w('  return bridge_multi_ii(ctx, r);\n')
            else:
                assert ret in TYPES, (exp['name'], ret)
                w(f'  return bridge_to_js_{ret}(r);\n')
        w('}\n\n')

    w(f'const int bridge_export_count = {len(funcs)};\n')
    w('const BridgeExport bridge_exports[] = {\n')
    for idx, exp in enumerate(funcs):
        w(f'  {{{c_string(exp["name"])}, export_{idx}, {len(exp["params"])}}},\n')
    w('};\n\n')

    memories = [e for e in exports if e['kind'] == 'wasm_rt_memory_t']
    tables = [e for e in exports if e['kind'] == 'wasm_rt_externref_table_t']
    assert len(memories) == 1 and len(tables) == 1, (memories, tables)
    w(f'const char *const bridge_memory_export = {c_string(memories[0]["name"])};\n')
    w(f'wasm_rt_memory_t *bridge_memory(void) {{ return {memories[0]["cname"]}(&g_inst); }}\n')
    w(f'const char *const bridge_table_export = {c_string(tables[0]["name"])};\n')
    w(f'wasm_rt_externref_table_t *bridge_externref_table(void) {{ return {tables[0]["cname"]}(&g_inst); }}\n')
    return len(glue), len(funcs)


def main():
    imports, exports = parse(sys.argv[1])
    with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as out:
        n_imp, n_exp = emit(imports, exports, out)
    wasi = sorted(i['name'] for i in imports if i['module'] == WASI_MODULE)
    print(f'{n_imp} glue imports, {n_exp} function exports; WASI: {" ".join(wasi)}')


if __name__ == '__main__':
    main()
